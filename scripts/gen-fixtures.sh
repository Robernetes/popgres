#!/usr/bin/env bash
#
# Regenerates tests/data/data.pg.sql, the Postgres fixtures of the test suite,
# from the PocketBase test data (tests/data/data.db and auxiliary.db).
#
# It imports the SQLite data with popgres-import into a throwaway Postgres 17
# container and dumps it with pg_dump 17 as plain INSERT statements, so that
# the result loads in Postgres 17 and 18 with any client (no psql meta commands).
#
# Requires docker and go.
#
#   ./scripts/gen-fixtures.sh

set -euo pipefail

cd "$(dirname "$0")/.."

IMAGE="pgvector/pgvector:0.8.7-pg17-trixie"
CONTAINER="popgres_gen_fixtures"
PORT="${GEN_FIXTURES_PORT:-5499}"
PASSWORD="fixtures"
OUT="tests/data/data.pg.sql"

export MSYS_NO_PATHCONV=1

cleanup() {
  docker rm -f "$CONTAINER" >/dev/null 2>&1 || true
}
trap cleanup EXIT

cleanup
docker run -d --name "$CONTAINER" -p "127.0.0.1:${PORT}:5432" -e POSTGRES_PASSWORD="$PASSWORD" "$IMAGE" >/dev/null

# wait over TCP to skip the temporary server of the first initialization
for _ in $(seq 1 90); do
  if docker exec "$CONTAINER" pg_isready -h 127.0.0.1 -U postgres -q; then
    break
  fi
  sleep 1
done
docker exec "$CONTAINER" pg_isready -h 127.0.0.1 -U postgres

docker exec "$CONTAINER" psql -U postgres -v ON_ERROR_STOP=1 -q -c "CREATE DATABASE fixtures"
docker exec "$CONTAINER" psql -U postgres -d fixtures -v ON_ERROR_STOP=1 -q \
  -c "CREATE EXTENSION IF NOT EXISTS vector" \
  -c "CREATE EXTENSION IF NOT EXISTS pgcrypto"

go run ./cmd/popgres-import \
  -db "postgres://postgres:${PASSWORD}@127.0.0.1:${PORT}/fixtures?sslmode=disable" \
  tests/data

{
  echo "-- popgres test fixtures generated by scripts/gen-fixtures.sh from tests/data/data.db and auxiliary.db."
  echo "-- Do not edit manually. The extensions (vector, pgcrypto) are provided by the test template database."
  echo
  docker exec "$CONTAINER" pg_dump -U postgres -d fixtures \
    --inserts --rows-per-insert=50 \
    --no-owner --no-privileges --no-comments \
    --exclude-extension=vector --exclude-extension=pgcrypto |
    grep -v -E '^\\(restrict|unrestrict) ' |
    tr -d '\r'
} > "$OUT"

echo "generated $OUT ($(wc -l < "$OUT") lines)"
