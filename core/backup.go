package core

import (
	"context"
	"fmt"
	"log/slog"
	"sort"
	"time"

	"github.com/Robernetes/popgres/tools/inflector"
)

const (
	StoreKeyActiveBackup = "@activeBackup"
)

const (
	// backupLockName is the cluster lock held during a backup operation
	// (it prevents concurrent backups by multiple app instances).
	backupLockName = "backup"

	// kvKeyActiveBackup is the shared key with the name of the active backup.
	kvKeyActiveBackup = "@activeBackup"

	// kvActiveBackupTTL is the max duration of the active backup shared key
	// (it is deleted when the backup completes and the cluster lock is the
	// actual indicator of an active backup).
	kvActiveBackupTTL = 24 * time.Hour
)

// IsBackupActive reports whether a backup operation is in progress
// in the current or in another app instance (node).
func IsBackupActive(app App) bool {
	if app.Store().Has(StoreKeyActiveBackup) {
		return true
	}

	locked, err := app.Cluster().IsLocked(context.Background(), backupLockName)
	if err != nil {
		app.Logger().Warn("Failed to check the backup cluster lock", slog.String("error", err.Error()))
		return false
	}

	return locked
}

// ActiveBackupName returns the name of the backup that is being created in
// the current or in another app instance (node), or an empty string if none.
func ActiveBackupName(app App) string {
	if app.Store().Has(StoreKeyActiveBackup) {
		name, _ := app.Store().Get(StoreKeyActiveBackup).(string)
		return name
	}

	locked, err := app.Cluster().IsLocked(context.Background(), backupLockName)
	if err != nil || !locked {
		return ""
	}

	name, _, _ := app.Cluster().KV().Get(kvKeyActiveBackup)

	return name
}

// generateBackupName generates a new backup name based on the app name and current date.
func generateBackupName(app App, prefix string) string {
	appName := inflector.Snakecase(app.Settings().Meta.AppName)
	if len(appName) > 50 {
		appName = appName[:50]
	}

	return fmt.Sprintf(
		"%s%s_%s.zip",
		prefix,
		appName,
		time.Now().UTC().Format("20060102150405"),
	)
}

// registerAutobackupHooks registers the autobackup app serve hooks.
func (app *BaseApp) registerAutobackupHooks() {
	const jobId = "__pbAutoBackup__"

	loadJob := func() {
		rawSchedule := app.Settings().Backups.Cron
		if rawSchedule == "" {
			app.Cron().Remove(jobId)
			return
		}

		app.Cron().Add(jobId, rawSchedule, func() {
			const autoPrefix = "@auto_pb_backup_"

			name := generateBackupName(app, autoPrefix)

			if err := app.CreateBackup(context.Background(), name); err != nil {
				app.Logger().Error(
					"[Backup cron] Failed to create backup",
					slog.String("name", name),
					slog.String("error", err.Error()),
				)

				alertError := sendSystemAlertToAllSuperusers(
					app,
					"Autobackup failure",
					"Failed to create/upload automated backup. Raw error:\n"+err.Error(),
				)
				if alertError != nil {
					app.Logger().Warn(
						"[Backup cron] Failed to send backup error alerts",
						slog.String("name", name),
						slog.String("error", alertError.Error()),
					)
				}
			}

			maxKeep := app.Settings().Backups.CronMaxKeep

			if maxKeep == 0 {
				return // no explicit limit
			}

			fsys, err := app.NewBackupsFilesystem()
			if err != nil {
				app.Logger().Error(
					"[Backup cron] Failed to initialize the backup filesystem",
					slog.String("error", err.Error()),
				)
				return
			}
			defer fsys.Close()

			files, err := fsys.List(autoPrefix)
			if err != nil {
				app.Logger().Error(
					"[Backup cron] Failed to list autogenerated backups",
					slog.String("error", err.Error()),
				)
				return
			}

			if maxKeep >= len(files) {
				return // nothing to remove
			}

			// sort desc
			sort.Slice(files, func(i, j int) bool {
				return files[i].ModTime.After(files[j].ModTime)
			})

			// keep only the most recent n auto backup files
			toRemove := files[maxKeep:]

			for _, f := range toRemove {
				if err := fsys.Delete(f.Key); err != nil {
					app.Logger().Error(
						"[Backup cron] Failed to remove old autogenerated backup",
						slog.String("key", f.Key),
						slog.String("error", err.Error()),
					)
				}
			}
		})
	}

	app.OnBootstrap().BindFunc(func(e *BootstrapEvent) error {
		if err := e.Next(); err != nil {
			return err
		}

		loadJob()

		return nil
	})

	app.OnSettingsReload().BindFunc(func(e *SettingsReloadEvent) error {
		if err := e.Next(); err != nil {
			return err
		}

		loadJob()

		return nil
	})
}
